-- =====================================================================
-- Миграция: 20260907000002_add_orders_closed_at.sql
-- Описание: колонка closed_at в orders — момент фактического закрытия
--           заказа (статус «Закрыт»). Заполняется RPC закрытия заказа;
--           исторические заказы остаются с NULL.
-- Применение: Supabase SQL Editor (или supabase db push).
-- =====================================================================

alter table orders
  add column if not exists closed_at timestamptz;
